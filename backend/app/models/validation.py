from datetime import datetime
from sqlalchemy import (
    Boolean,
    Column,
    DateTime,
    Float,
    ForeignKey,
    Integer,
    JSON,
    String,
    Text,
)
from sqlalchemy.orm import relationship
from backend.app.database import Base


class IssueSeverity:
    CRITICAL = "CRITICAL"
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"
    INFO = "INFO"


class IssueStatus:
    OPEN = "OPEN"
    ASSIGNED = "ASSIGNED"
    CORRECTION_REQUESTED = "CORRECTION_REQUESTED"
    FALSE_POSITIVE = "FALSE_POSITIVE"
    RESOLVED = "RESOLVED"


class VersionedRule(Base):
    __tablename__ = "versioned_rules"

    id = Column(Integer, primary_key=True, index=True)
    rule_code = Column(String(100), index=True, nullable=False)  # e.g., "APAAR_PRESENCE_CHECK", "INTAKE_CAPACITY_CHECK"
    rule_version = Column(String(50), default="v2026.1", nullable=False)
    rule_name = Column(String(255), nullable=False)
    description = Column(Text, nullable=False)
    severity = Column(String(20), default=IssueSeverity.HIGH, nullable=False)
    is_active = Column(Boolean, default=True, nullable=False)
    config_payload = Column(JSON, nullable=True)  # Parameters, thresholds, regexes, etc.
    created_at = Column(DateTime, default=datetime.utcnow, nullable=False)


class ValidationIssue(Base):
    """
    Validation issue generated by deterministic rules or secondary anomaly signals.
    Identifies triggering rule, rule version, affected records, severity, evidence, reviewer, and status.
    """
    __tablename__ = "validation_issues"

    id = Column(Integer, primary_key=True, index=True)
    validation_run_id = Column(Integer, ForeignKey("validation_runs.id", ondelete="SET NULL"), nullable=True, index=True)
    upload_batch_id = Column(Integer, ForeignKey("upload_batches.id", ondelete="SET NULL"), nullable=True, index=True)
    rule_id = Column(Integer, ForeignKey("versioned_rules.id", ondelete="SET NULL"), nullable=True, index=True)

    rule_code = Column(String(100), nullable=False, index=True)
    rule_version = Column(String(50), default="v2026.1", nullable=False)
    severity = Column(String(20), default=IssueSeverity.HIGH, nullable=False, index=True)

    institution_id = Column(Integer, ForeignKey("institutions.id", ondelete="CASCADE"), nullable=False, index=True)
    programme_id = Column(Integer, ForeignKey("programmes.id", ondelete="SET NULL"), nullable=True, index=True)
    academic_year_id = Column(Integer, ForeignKey("academic_years.id", ondelete="CASCADE"), nullable=False, index=True)

    affected_student_enrolment_id = Column(Integer, ForeignKey("student_enrolments.id", ondelete="SET NULL"), nullable=True, index=True)
    affected_staging_row_id = Column(Integer, ForeignKey("upload_staging_rows.id", ondelete="SET NULL"), nullable=True, index=True)

    title = Column(String(255), nullable=False)
    description = Column(Text, nullable=False)
    evidence_details = Column(JSON, nullable=False)  # Sourced rule, declared vs actual, duplicates list, diff, etc.

    status = Column(String(50), default=IssueStatus.OPEN, nullable=False, index=True)
    assigned_to_user_id = Column(Integer, ForeignKey("users.id", ondelete="SET NULL"), nullable=True, index=True)
    reviewer_notes = Column(Text, nullable=True)
    resolution_reason = Column(Text, nullable=True)

    detected_at = Column(DateTime, default=datetime.utcnow, nullable=False)
    resolved_at = Column(DateTime, nullable=True)

    institution = relationship("Institution")
    programme = relationship("Programme")
    academic_year = relationship("AcademicYear")
    upload_batch = relationship("UploadBatch", back_populates="issues")
    validation_run = relationship("ValidationRun", back_populates="issues")
    versioned_rule = relationship("VersionedRule")
    assigned_to = relationship("User", foreign_keys=[assigned_to_user_id])
    affected_enrolment = relationship("StudentEnrolment")
    affected_staging_row = relationship("UploadStagingRow")
    review_decisions = relationship("ReviewDecision", back_populates="validation_issue")


class DuplicateCandidateGroup(Base):
    """
    A candidate duplicate group requiring human review.
    Does NOT establish guilt or trigger automatic adverse decisions.
    """
    __tablename__ = "duplicate_candidate_groups"

    id = Column(Integer, primary_key=True, index=True)
    rule_code = Column(String(100), nullable=False, default="CROSS_INSTITUTION_DUPLICATE_CANDIDATE")
    match_type = Column(String(50), default="EXACT_FINGERPRINT", nullable=False)  # EXACT_FINGERPRINT, CROSS_INSTITUTION_NAME_DOB
    status = Column(String(50), default="PENDING_REVIEW", nullable=False, index=True)  # PENDING_REVIEW, CONFIRMED_DUPLICATE, LEGITIMATE_TRANSFER, FALSE_POSITIVE
    review_notes = Column(Text, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow, nullable=False)
    resolved_at = Column(DateTime, nullable=True)

    members = relationship("DuplicateCandidateMember", back_populates="group", cascade="all, delete-orphan")
    review_decisions = relationship("ReviewDecision", back_populates="duplicate_group")


class DuplicateCandidateMember(Base):
    __tablename__ = "duplicate_candidate_members"

    id = Column(Integer, primary_key=True, index=True)
    duplicate_group_id = Column(Integer, ForeignKey("duplicate_candidate_groups.id", ondelete="CASCADE"), nullable=False, index=True)
    student_identity_id = Column(Integer, ForeignKey("student_identities.id", ondelete="CASCADE"), nullable=False, index=True)
    student_enrolment_id = Column(Integer, ForeignKey("student_enrolments.id", ondelete="CASCADE"), nullable=False, index=True)
    institution_id = Column(Integer, ForeignKey("institutions.id", ondelete="CASCADE"), nullable=False, index=True)
    match_confidence = Column(Float, default=1.0, nullable=False)
    created_at = Column(DateTime, default=datetime.utcnow, nullable=False)

    group = relationship("DuplicateCandidateGroup", back_populates="members")
    student_identity = relationship("StudentIdentity")
    student_enrolment = relationship("StudentEnrolment")
    institution = relationship("Institution")
